"""Generates the test table and main() of a module's test executable.

Finds every NX_TEST(Suite, Name) in the given sources and writes a C++ file that declares the test functions,
lists them in a constant table in source order, and passes the table to Nexyl::Test::RunTestsMain.

Tests are registered by this generated table instead of static constructors, which the engine forbids
(rule INIT-1). The output file is rewritten only when its content changes, so an unchanged module does not
recompile.
"""

from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "ci"))
import nexyl_ci  # noqa: E402  (shared C++ lexer)

_TEST = re.compile(r"\bNX_TEST\s*\(\s*([A-Za-z_]\w*)\s*,\s*([A-Za-z_]\w*)\s*\)")
_OPENING_CONDITIONAL = re.compile(r"^\s*#\s*(if|ifdef|ifndef)\b")
_CLOSING_CONDITIONAL = re.compile(r"^\s*#\s*endif\b")


@dataclass(frozen=True)
class FoundTest:
    suite: str
    name: str
    path: Path
    line: int

    @property
    def function(self) -> str:
        return f"NxTest{self.suite}{self.name}"


class RegistryError(Exception):
    pass


def find_tests(path: Path) -> list[FoundTest]:
    """Every NX_TEST in one source file, in order. Fails on an NX_TEST inside conditional compilation."""
    text = path.read_text(encoding="utf-8")
    _, code = nexyl_ci.strip_cpp(text)

    found: list[FoundTest] = []
    depth = 0
    for number, line in enumerate(code.split("\n"), start=1):
        if _OPENING_CONDITIONAL.match(line):
            depth += 1
            continue
        if _CLOSING_CONDITIONAL.match(line):
            depth -= 1
            continue
        if line.lstrip().startswith("#"):
            continue
        for match in _TEST.finditer(line):
            if depth > 0:
                raise RegistryError(
                    f"{path}:{number}: NX_TEST inside conditional compilation. "
                    "Register every test unconditionally and skip work inside the test body instead."
                )
            found.append(FoundTest(match.group(1), match.group(2), path, number))
    return found


def collect(sources: list[Path]) -> list[FoundTest]:
    tests: list[FoundTest] = []
    for source in sorted(sources):
        tests.extend(find_tests(source))

    seen_names: dict[tuple[str, str], FoundTest] = {}
    seen_functions: dict[str, FoundTest] = {}
    for test in tests:
        key = (test.suite, test.name)
        if key in seen_names:
            first = seen_names[key]
            raise RegistryError(
                f"{test.path}:{test.line}: test {test.suite}.{test.name} is already defined at "
                f"{first.path}:{first.line}."
            )
        if test.function in seen_functions:
            first = seen_functions[test.function]
            raise RegistryError(
                f"{test.path}:{test.line}: test {test.suite}.{test.name} and {first.suite}.{first.name} "
                f"({first.path}:{first.line}) produce the same function name {test.function}. Rename one of them."
            )
        seen_names[key] = test
        seen_functions[test.function] = test
    return tests


def render(tests: list[FoundTest], repo: Path, module: str) -> str:
    lines = [
        f"// Test registry of module {module}.",
        "// Generated by Scripts/build/generate_test_registry.py from the module's Tests/ sources. Do not edit.",
        "",
        "#include <Nexyl/Test/Runner.h>",
        "",
    ]
    lines += [f"void {test.function}();" for test in tests]
    if tests:
        lines += ["", "namespace {", "", "constexpr ::Nexyl::Test::TestCase kTests[] = {"]
        for test in tests:
            file = nexyl_ci.relative_path(test.path, repo)
            lines.append(f'    {{"{test.suite}", "{test.name}", &{test.function}, "{file}", {test.line}}},')
        lines += ["};", "", "} // namespace", ""]
        table = "::Nexyl::Span<const ::Nexyl::Test::TestCase>(kTests)"
    else:
        lines.append("")
        table = "::Nexyl::Span<const ::Nexyl::Test::TestCase>()"
    lines += [
        "int main(int argumentCount, char** arguments) {",
        f"    return ::Nexyl::Test::RunTestsMain({table}, argumentCount, arguments);",
        "}",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--repo", type=Path, required=True, help="repository root")
    parser.add_argument("--module", required=True, help="module name, for the file header")
    parser.add_argument("--output", type=Path, required=True, help="generated C++ file")
    parser.add_argument("sources", type=Path, nargs="+", help="the module's test sources")
    arguments = parser.parse_args()

    try:
        tests = collect([source.resolve() for source in arguments.sources])
    except RegistryError as error:
        print(f"error: {error}", file=sys.stderr)
        return 1

    content = render(tests, arguments.repo.resolve(), arguments.module)
    output: Path = arguments.output
    if not output.exists() or output.read_text(encoding="utf-8") != content:
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(content, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
